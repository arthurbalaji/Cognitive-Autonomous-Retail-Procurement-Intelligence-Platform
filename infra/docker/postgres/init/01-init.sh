#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<EOSQL
CREATE ROLE carpip_app LOGIN PASSWORD '${CARPIP_DB_PASSWORD}';
CREATE ROLE carpip_intel LOGIN PASSWORD '${CARPIP_INTEL_DB_PASSWORD}';
CREATE ROLE pos_app LOGIN PASSWORD '${POS_DB_PASSWORD}';
CREATE ROLE erp_app LOGIN PASSWORD '${ERP_DB_PASSWORD}';
CREATE DATABASE carpip OWNER carpip_app;
CREATE DATABASE pos OWNER pos_app;
CREATE DATABASE erp OWNER erp_app;
REVOKE CONNECT ON DATABASE carpip FROM PUBLIC;
REVOKE CONNECT ON DATABASE pos FROM PUBLIC;
REVOKE CONNECT ON DATABASE erp FROM PUBLIC;
GRANT CONNECT ON DATABASE carpip TO carpip_intel;
EOSQL
